def width(font,s,gap=1,space=4):
    w=0
    for i,ch in enumerate(s):
        w+=space if ch==' ' else len(font[ch][0])
        if i<len(s)-1: w+=gap
    return w
def draw(px,font,s,x,y,color,gap=1,space=4):
    """draw string into 2D index list px; returns set of (x,y) ink pixels"""
    ink=set()
    for ch in s:
        if ch==' ': x+=space+gap; continue
        g=font[ch]
        for gy,row in enumerate(g):
            for gx,c in enumerate(row):
                if c=='#': px[y+gy][x+gx]=color; ink.add((x+gx,y+gy))
        x+=len(g[0])+gap
    return ink

